"""Builds app/ui/mark-data.js, the moving mark of the window, from the official mark (white fish on the turquoise plate).

Usage: python src/mark.py <marque/kit/declinaisons/blanc-sur-turquoise.svg>
The white shape stays one path; each point gets the part it belongs to (tail, rod, eye, little fin) and how much it turns,
so app/ui/mark.js bends the path instead of turning cut pieces (a cut piece shows a step at the joint while it turns).
Needs numpy and shapely.
"""
import json, os, re, sys
import numpy as np
from shapely.geometry import Point, Polygon, box

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
svg = open(sys.argv[1], encoding='utf-8').read()
inner_open = re.search(r'<g transform="matrix\([^"]+\)">', svg).group(0)
paths = re.findall(r'<path [^>]*/>', svg)
circles = re.findall(r'<circle [^>]*/>', svg)
if len(paths) != 4 or len(circles) != 3:
    sys.exit('Unexpected mark: 4 paths and 3 circles were expected')
body, mouth, eye, tip = paths
halo1, halo2, lamp = circles
plate = re.search(r'<rect [^>]*/>', svg).group(0)
a, b, c, d, e, f = [float(v) for v in re.search(r'matrix\(([^)]+)\)', svg).group(1).split()]
M = np.array([[a, c, e], [b, d, f], [0, 0, 1]])


def rings(dstr, per=12):
    out, cur = [], None
    toks = re.findall(r'[MCZ]|-?\d*\.?\d+(?:e-?\d+)?', dstr)
    i = 0
    while i < len(toks):
        k = toks[i]
        i += 1
        if k == 'M':
            cur = np.array([float(toks[i]), float(toks[i + 1])])
            i += 2
            out.append([cur])
        elif k == 'C':
            p = [np.array([float(toks[i + 2 * j]), float(toks[i + 2 * j + 1])]) for j in range(3)]
            i += 6
            for s in np.linspace(0, 1, per + 1)[1:]:
                out[-1].append((1 - s) ** 3 * cur + 3 * (1 - s) ** 2 * s * p[0] + 3 * (1 - s) * s ** 2 * p[1] + s ** 3 * p[2])
            cur = p[2]
    return [(M @ np.c_[np.array(r), np.ones(len(r))].T).T[:, :2] for r in out]


outline = rings(re.search(r'd="([^"]+)"', body).group(1))
if len(outline) != 3:
    sys.exit('Unexpected body: outline, eye and little fin were expected')
shape = Polygon(outline[0], outline[1:]).buffer(0)

# The rod is the thin part of the shape above the head: an opening wider than the rod keeps the head and drops the rod.
area = box(272, 22, 512, 272)
core = shape.intersection(area).buffer(-11).buffer(11)
rod = shape.intersection(area).difference(core)
rod = max(getattr(rod, 'geoms', [rod]), key=lambda g: g.area)
foot = rod.intersection(core.buffer(3)).centroid
root = (round(foot.x, 1), round(foot.y, 1))
rod_zone = rod.buffer(2)
far = max(np.array(rod.exterior.coords), key=lambda p: np.hypot(p[0] - root[0], p[1] - root[1]))
rod_len = float(np.hypot(far[0] - root[0], far[1] - root[1]))

TAIL_PIVOT, TAIL_FROM, TAIL_TO = (190.0, 244.0), 190.0, 72.0
smooth = lambda w: round(w * w * (3 - 2 * w), 3)
pts = []
for n, r in enumerate(outline):
    ring = []
    for x, y in r:
        if n:
            ring.append([round(x, 1), round(y, 1), 2 + n, 1])
        elif x < TAIL_FROM:
            ring.append([round(x, 1), round(y, 1), 1, smooth(min(1.0, (TAIL_FROM - x) / (TAIL_FROM - TAIL_TO)))])
        elif rod_zone.contains(Point(x, y)):
            ring.append([round(x, 1), round(y, 1), 2, smooth(min(1.0, np.hypot(x - root[0], y - root[1]) / rod_len))])
        else:
            ring.append([round(x, 1), round(y, 1), 0, 0])
    pts.append(ring)

eye_ring, fin_ring = Polygon(outline[1]), Polygon(outline[2])
ey = eye_ring.centroid
fb = fin_ring.bounds
data = {
    'plate': plate, 'inner': inner_open,
    'mouth': mouth, 'eye': eye, 'tip': tip, 'halos': halo1 + halo2, 'lamp': lamp,
    'rings': pts, 'tail': TAIL_PIVOT, 'root': root,
    'light': [round(float(v), 1) for v in (M @ np.array([168, 142, 1]))[:2]],
    'lid': round(ey.y + (eye_ring.bounds[3] - ey.y) * .6, 1),
    'fin': [round(fb[2] - 5, 1), round((fb[1] + fb[3]) / 2, 1)],
}
out = os.path.join(ROOT, 'app', 'ui', 'mark-data.js')
with open(out, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write("'use strict';\n\n// Generated by src/mark.py from the official mark: do not edit by hand.\nconst MARK_DATA = " + json.dumps(data, separators=(',', ':')) + ';\n')
print(sum(len(r) for r in pts), 'points, rod foot', root, 'rod', round(rod_len), 'bytes', os.path.getsize(out))
